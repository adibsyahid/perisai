// Turns the official Malaysia state boundaries into small SVG paths for the Radar map.
// Source: data.gov.my (DOSM) open-source frontend, MIT licence:
//   github.com/data-gov-my/datagovmy-front → packages/datagovmy-ui/src/lib/geojson/state/_mobile.ts
// That "mobile" layout places Sabah and Sarawak near the peninsula so the map fits a phone.
//
// Run once (the output is committed, so phones never download the 600 KB original):
//   node scripts/make-radar-map.mjs "<path to downloaded _mobile.ts>"
import { readFile, writeFile } from "node:fs/promises";
import { geoMercator, geoPath } from "d3-geo";

const WIDTH = 360;
const PAD = 6;
const MIN_STEP = 0.9; // px: drop points closer than this to the previous one
const MIN_RING_AREA = 3; // px²: drop specks of tiny islands

// The file is a TypeScript module holding one object literal. We turn it into JSON
// with text rules instead of running it, because it is downloaded data, not our code.
function parseObjectLiteral(source) {
  const json = source
    .replace(/^\s*export default\s*/, "")
    .replace(/;\s*$/, "")
    .replace(/([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:/g, '$1"$2":') // quote keys
    .replace(/,(\s*[}\]])/g, "$1"); // drop trailing commas
  return JSON.parse(json);
}

const ID_BY_NAME = {
  Johor: "johor", Kedah: "kedah", Kelantan: "kelantan", Melaka: "melaka",
  "Negeri Sembilan": "negeri_sembilan", Pahang: "pahang", Perak: "perak", Perlis: "perlis",
  "Pulau Pinang": "pulau_pinang", Sabah: "sabah", Sarawak: "sarawak", Selangor: "selangor",
  Terengganu: "terengganu", "W.P. Kuala Lumpur": "kuala_lumpur", "W.P. Labuan": "labuan",
  "W.P. Putrajaya": "putrajaya",
};

const ringArea = (pts) =>
  Math.abs(pts.reduce((sum, [x, y], i) => {
    const [nx, ny] = pts[(i + 1) % pts.length];
    return sum + x * ny - nx * y;
  }, 0)) / 2;

const file = process.argv[2];
if (!file) throw new Error('Usage: node scripts/make-radar-map.mjs "<path to _mobile.ts>"');
const collection = parseObjectLiteral(await readFile(file, "utf8"));

const projection = geoMercator().fitWidth(WIDTH - PAD * 2, collection);
const [[, y0], [, y1]] = geoPath(projection).bounds(collection);
projection.translate([projection.translate()[0] + PAD, projection.translate()[1] - y0 + PAD]);
const height = Math.ceil(y1 - y0 + PAD * 2);
const path = geoPath(projection);

const states = collection.features.map((feature) => {
  const id = ID_BY_NAME[feature.properties.state];
  if (!id) throw new Error(`Unknown state name: ${feature.properties.state}`);

  const polygons = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  let d = "";
  for (const polygon of polygons) {
    for (const ring of polygon) {
      const kept = [];
      for (const point of ring) {
        const [x, y] = projection(point);
        const last = kept[kept.length - 1];
        if (!last || Math.hypot(x - last[0], y - last[1]) >= MIN_STEP) kept.push([x, y]);
      }
      if (kept.length < 3 || ringArea(kept) < MIN_RING_AREA) continue;
      d += "M" + kept.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z";
    }
  }
  const [cx, cy] = path.centroid(feature);
  return { id, d, cx: Number(cx.toFixed(1)), cy: Number(cy.toFixed(1)) };
});

const output = `// Generated by scripts/make-radar-map.mjs. Do not edit by hand.
// State boundaries © data.gov.my (DOSM), MIT licence. Simplified for a ${WIDTH}px-wide phone map.
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${height};
export const MAP_STATES: { id: string; d: string; cx: number; cy: number }[] = ${JSON.stringify(states)};
`;
await writeFile("src/lib/radar-map.ts", output);
console.log(`Wrote src/lib/radar-map.ts: ${states.length} states, ${WIDTH}x${height}, ${(output.length / 1024).toFixed(0)} KB`);
